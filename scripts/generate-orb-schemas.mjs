// Generates workers/claims/src/orb-schemas.ts from registry meta.ts files.
// Parses param/color metadata with regex so WebGPU shader code is never imported.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const orbsDir = join(root, "registry/components/orbs");
const outFile = join(root, "workers/claims/src/orb-schemas.ts");

const slugs = [];
const schemas = {};

for (const entry of readdirSync(orbsDir, { withFileTypes: true })) {
  if (!entry.isDirectory() || !entry.name.startsWith("orb-")) {
    continue;
  }
  const metaPath = join(orbsDir, entry.name, "meta.ts");
  let text;
  try {
    text = readFileSync(metaPath, "utf-8");
  } catch {
    continue;
  }
  const slugMatch = text.match(/slug:\s*"([^"]+)"/);
  const slug = slugMatch?.[1] ?? entry.name;
  slugs.push(slug);

  const params = [];
  const paramBlock = text.match(/params:\s*\[(.*?)\]\s*,\s*\n?\s*shader:/s);
  if (paramBlock) {
    const re =
      /\{\s*default:[^}]*?key:\s*"([^"]+)"[^}]*?max:\s*([0-9.eE+-]+)[^}]*?min:\s*([0-9.eE+-]+)[^}]*?step:\s*([0-9.eE+-]+)/gs;
    for (const m of paramBlock[1].matchAll(re)) {
      params.push({
        key: m[1],
        max: Number(m[2]),
        min: Number(m[3]),
        step: Number(m[4]),
      });
    }
  }
  const colors = [];
  const colorsBlock = text.match(/colors:\s*\[(.*?)\]/s);
  if (colorsBlock) {
    for (const m of colorsBlock[1].matchAll(/key:\s*"([^"]+)"/g)) {
      colors.push(m[1]);
    }
  }
  schemas[slug] = { colors, params };
}

slugs.sort();

const header = `// AUTO-GENERATED by scripts/generate-orb-schemas.mjs — do not edit by hand.\n// Snapshot of shipped orb param/color schemas for deterministic claim orbs.\n\nexport const ORB_SLUGS = ${JSON.stringify(slugs)} as const;\n\nexport interface OrbParamSchema {\n  key: string;\n  min: number;\n  max: number;\n  step: number;\n}\n\nexport interface OrbVariantSchema {\n  slug: string;\n  params: OrbParamSchema[];\n  colors: string[];\n}\n\nexport const ORB_SCHEMAS: Record<string, OrbVariantSchema> = `;
const body = JSON.stringify(
  Object.fromEntries(
    slugs.map((s) => [
      s,
      {
        colors: schemas[s]?.colors ?? [],
        params: schemas[s]?.params ?? [],
        slug: s,
      },
    ])
  ),
  null,
  2
);

writeFileSync(`${outFile}`, `${header}${body};\n`);
console.log(`wrote ${outFile} (${slugs.length} variants)`);
